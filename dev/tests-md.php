<?php

declare(strict_types=1);

/**
 * dev/TESTS.md from a ci log (dev/dev.sh ci writes storage/ci.log): every "ok" line of the smoke, e2e and Chrome
 * suites as a sentence under the heading the suite printed before it. What is tested, readable without the code.
 * Run: php dev/tests-md.php <ci.log>
 */

$log = file($argv[1] ?? throw new RuntimeException('Usage: php dev/tests-md.php <ci.log>'), FILE_IGNORE_NEW_LINES) ?: [];
$suites = ['smoke' => 'Smoke (console, `dev/smoke.php`)', 'e2e' => 'Control panel over HTTP (`dev/e2e.php`)', 'ui' => 'Control panel in Chrome (`dev/ui.mts`)'];
$suite = 'smoke';
$heading = '';
/** @var array<string, array<string, list<string>>> $spec suite => heading => sentences */
$spec = [];
foreach ($log as $line) {
    if (preg_match('/^(?:Craft running at|Logging in|Starting Chrome)/', $line)) {
        // each suite after the smoke starts the dev server: the first time for e2e, the second for the Chrome suite
        $suite = match (true) {
            str_starts_with($line, 'Starting Chrome') => 'ui',
            str_starts_with($line, 'Craft running at') => $suite === 'smoke' ? 'e2e' : 'ui',
            default => $suite === 'smoke' ? 'e2e' : $suite,
        };
        $heading = '';
        continue;
    }
    if (preg_match('/^\s+(ok|FAIL)\s+(.*)$/', $line, $m)) {
        // the numbers in a sentence are this run's (ids, counts); the sentence is the test
        $spec[$suite][$heading][] = ($m[1] === 'FAIL' ? '✗ ' : '') . (preg_replace(['/\s*\(HTTP \d+.*$/', '/\s*\((?>[^()]+|\([^()]*\))*\)\s*$/'], '', $m[2]) ?? $m[2]); // atomic: long messages never backtrack out; an HTTP detail may be cut off mid-way
    } elseif (preg_match('/^\S.{2,}$/', $line) && !preg_match('/^(\d+ ok|\[|Exception|PHP |#\d|Stack)/', $line)) {
        $heading = rtrim($line, ': ');
    }
}
echo "# What the tests cover\n\nGenerated by `dev/tests-md.php` from the last `dev/dev.sh ci` run; one line per assertion, grouped by the heading the suite printed. Do not edit by hand.\n";
foreach ($suites as $key => $title) {
    if (empty($spec[$key])) {
        continue;
    }
    echo "\n## $title\n";
    foreach ($spec[$key] as $section => $sentences) {
        echo $section !== '' ? "\n### $section\n\n" : "\n";
        foreach (array_values(array_unique($sentences)) as $sentence) {
            echo "- $sentence\n";
        }
    }
}
